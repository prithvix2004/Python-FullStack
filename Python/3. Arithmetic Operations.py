a = float(input("Enter first number : "))
b = float(input("Enter second number : "))

sum = a + b
print("Add : ", sum)

sub = a - b
print("Subtract : ", sub)

mul = a * b
print("Multiply : ", mul)

div = a / b
print("Divide : ", div)

floordiv = a // b
print("Floor Division : ", floordiv)

exp = a ** b
print("Exponent : ", exp)